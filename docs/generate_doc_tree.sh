#!/bin/bash

# THE TRANSMUTER - Final Recursive Tree Generator
ROOT_README="README.md"
SW_ROOT="sw"
ANCHOR="Project structure (generated by docs/generate_doc_tree.sh):"

# 1. Get a list of all directories and their README summaries
# We create a map of "path:summary"
TEMP_MAP="map.tmp"
> "$TEMP_MAP"

find "$SW_ROOT" -type d | while read -r dir; do
    if [ -f "$dir/README.md" ]; then
        SUMMARY=$(head -n 1 "$dir/README.md" | sed 's/^#* //;s/^[[:space:]]*//;s/[[:space:]]*$//')
        echo "$dir|$SUMMARY" >> "$TEMP_MAP"
    fi
done

# 2. Generate the tree and annotate it line-by-line
# We use tree -df to get full paths for matching, then strip them back for beauty
# We also prepend 4 spaces to every line for indentation
ANNOTATED_TREE=$(tree -df "$SW_ROOT" | grep -v 'directories' | while read -r line; do
    # Extract the full path from the tree line (the part that looks like sw/core/inc)
    FULL_PATH=$(echo "$line" | grep -o "$SW_ROOT/[^ ]*")
    
    # If we found a path, check our map for a summary
    if [ -n "$FULL_PATH" ]; then
        SUMMARY=$(grep "^$FULL_PATH|" "$TEMP_MAP" | cut -d'|' -f2)
        # Strip the full path from the line to keep the ASCII tree pretty
        CLEAN_LINE=$(echo "$line" | sed "s|$FULL_PATH|$(basename "$FULL_PATH")|")
        
        if [ -n "$SUMMARY" ]; then
            RESULT_LINE="$CLEAN_LINE  # $SUMMARY"
        else
            RESULT_LINE="$CLEAN_LINE"
        fi
    else
        # This handles the root "sw" line
        RESULT_LINE="$line"
    fi
    
    # Indent the line by 4 spaces
    echo "    $RESULT_LINE"
done)

# 3. Final Formatting & Replacement
printf "%s\n" "$ANNOTATED_TREE" > tree_block.tmp

awk -v anchor="$ANCHOR" '
BEGIN { skipping = 0 }
{
    if ($0 == anchor) {
        print $0
        while ((getline line < "tree_block.tmp") > 0) {
            print line
        }
        skipping = 1
        next
    }
    # Resume printing after the tree ends (next blank line or header)
    if (skipping && ($0 == "" || $0 ~ /^#/)) {
        skipping = 0
    }
    if (!skipping) {
        print $0
    }
}' "$ROOT_README" > README.tmp && mv README.tmp "$ROOT_README"

rm "$TEMP_MAP" tree_block.tmp