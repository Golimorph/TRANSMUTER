#!/bin/bash

# THE TRANSMUTER - Final Recursive Tree Generator
ROOT_README="README.md"
SW_ROOT="sw"
ANCHOR="Project structure (generated by docs/generate_doc_tree.sh):"

# 1. Get a list of all directories and their README summaries
# We create a map of "path:summary"
TEMP_MAP="map.tmp"
> "$TEMP_MAP"

find "$SW_ROOT" -type d | while read -r dir; do
    if [ -f "$dir/README.md" ]; then
        SUMMARY=$(head -n 1 "$dir/README.md" | sed 's/^#* //;s/^[[:space:]]*//;s/[[:space:]]*$//')
        echo "$dir|$SUMMARY" >> "$TEMP_MAP"
    fi
done

# 2. Generate the tree and annotate it line-by-line
# Use IFS= to prevent 'read' from stripping leading spaces
ANNOTATED_TREE=$(tree -df "$SW_ROOT" | grep -v 'directories' | while IFS= read -r line; do
    # Extract the path (anything starting with sw/)
    FULL_PATH=$(echo "$line" | grep -o "$SW_ROOT[^ ]*")
    
    if [ -n "$FULL_PATH" ]; then
        # Look up the summary in our temp map
        SUMMARY=$(grep "^$FULL_PATH|" "$TEMP_MAP" | cut -d'|' -f2)
        
        # This is the trick: Swap the full path for the basename 
        # WITHOUT losing the leading ASCII characters from 'tree'
        # We use ${line%%$FULL_PATH*} to keep everything BEFORE the path
        PREFIX="${line%%$FULL_PATH*}"
        BASE=$(basename "$FULL_PATH")
        
        if [ -n "$SUMMARY" ]; then
            echo "    $PREFIX$BASE  # $SUMMARY"
        else
            echo "    $PREFIX$BASE"
        fi
    else
        # Handle the root 'sw' line or lines without paths
        echo "    $line"
    fi
done)

# 3. Final Formatting & Replacement
{
    echo '```text'
    printf "%s\n" "$ANNOTATED_TREE"
    echo '```'
} > tree_block.tmp

awk -v anchor="$ANCHOR" '
BEGIN { skipping = 0 }
{
    if ($0 == anchor) {
        print $0
        print ""
        while ((getline line < "tree_block.tmp") > 0) {
            print line
        }
        skipping = 1
        next
    }

    if (skipping && ($0 == "" || $0 ~ /^#/)) {
        skipping = 0
    }

    if (!skipping) {
        print $0
    }
}' "$ROOT_README" > README.tmp && mv README.tmp "$ROOT_README"

rm "$TEMP_MAP" tree_block.tmp
